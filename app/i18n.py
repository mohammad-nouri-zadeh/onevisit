def t_variant(key: str, variant: str | None, lang: str, **values: object) -> str:
    """`key_variant` (e.g. "final_check_online") when it exists, else `key`; never mixes languages:
    if `lang` has its own `key` but not the variant, the plain `key` in `lang` wins over English."""
    if variant:
        wanted, own = f"{key}_{variant}", STRINGS.get(lang, {})
        if wanted in own or (key not in own and any(wanted in STRINGS[x] for x in ("en", "it"))):
            return t(wanted, lang, **values)
    return t(key, lang, **values)
